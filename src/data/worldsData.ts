import { CSSWorld, Level } from '@/types';

// Helper to generate levels cleanly with rich content
function createLevel(
  id: number,
  worldId: number,
  title: string,
  titleHinglish: string,
  concept: string,
  conceptHinglish: string,
  explanation: string,
  explanationHinglish: string,
  exampleCode: string,
  initialCode: string,
  solutionCode: string,
  instructions: string,
  instructionsHinglish: string,
  targetElement: string,
  castleComponentChanged: string,
  challenges: Array<{ property: string; expectedValue: string | string[]; description: string; hint: string }>,
  typingCode: string,
  targetWpm: number,
  timeLimitSeconds: number,
  quizQuestions: Array<{
    id: string;
    question: string;
    questionHinglish?: string;
    options: string[];
    correctIndex: number;
    explanation: string;
    explanationHinglish?: string;
    conceptTag: string;
  }>,
  xpReward: number = 25
): Level {
  return {
    id,
    globalId: `world-${worldId}-level-${id}`,
    title,
    titleHinglish,
    concept,
    conceptHinglish,
    explanation,
    explanationHinglish,
    exampleCode,
    initialCode,
    solutionCode,
    instructions,
    instructionsHinglish,
    targetElement,
    castleComponentChanged,
    challenges,
    typingChallenge: {
      code: typingCode,
      targetWpm,
      timeLimitSeconds,
    },
    quiz: quizQuestions,
    xpReward,
  };
}

